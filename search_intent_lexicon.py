_MORPH_ANALYZER: Optional[object] = None
_MORPH_TRIED = False


def _lazy_morph():
    global _MORPH_ANALYZER, _MORPH_TRIED
    if _MORPH_TRIED:
        return _MORPH_ANALYZER
    _MORPH_TRIED = True
    try:
        import pymorphy3

        _MORPH_ANALYZER = pymorphy3.MorphAnalyzer()
    except ImportError:
        _MORPH_ANALYZER = None
    return _MORPH_ANALYZER


def expand_fluff_with_morphology(word: str) -> Set[str]:
    """Все словоформы по первому разбору pymorphy3 (нижний регистр). Пусто, если морфологии нет."""
    morph = _lazy_morph()
    if morph is None or not (word or "").strip():
        return set()
    w = word.strip()
    try:
        parsed = morph.parse(w)[0]
        out: Set[str] = set()
        for f in parsed.lexeme:
            fw = getattr(f, "word", None)
            if fw and len(fw) >= 2:
                out.add(fw.lower())
        return out
    except Exception:
        return set()


def _union_morph_seeds(seeds: tuple[str, ...]) -> FrozenSet[str]:
    acc: Set[str] = set()
    for lemma in seeds:
        lemma = (lemma or "").strip()
        if len(lemma) < 2:
            continue
        acc.update(expand_fluff_with_morphology(lemma))
    return frozenset(acc)


