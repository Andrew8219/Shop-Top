def strip_intent_phrases(text: str) -> str:
    """Удаляет негативные вводные и заданные многословные клише (без учёта регистра)."""
    t = (text or "").strip()
    if not t:
        return t
    combined = INTENT_NEGATIVE_PHRASES | INTENT_FLUFF_PHRASES
    for phrase in sorted(combined, key=len, reverse=True):
        t = re.sub(re.escape(phrase), " ", t, flags=re.IGNORECASE)
    return re.sub(r"\s+", " ", t).strip()


